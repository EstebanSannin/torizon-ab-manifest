#!/usr/bin/env bash
# Write the build conf (bblayers.conf, local.conf, auto.conf) for one torizon-ab
# build dir. Used by ci/build.sh; usable by hand for local builds.
#
# bblayers.conf is DERIVED from the bblayers template of the meta-torizon-bsp
# revision the manifest pins — the file upstream's setup-environment copies — so a
# manifest bump never needs a hand-maintained layer list. Our overlay layers
# (torizon-ab/overlay.xml) go in EXTRALAYERS, the slot upstream leaves for them.
#
# A layer the template lists but the manifest does not fetch is dropped with a
# warning: upstream's pinned template can lag behind the pinned layer set (e.g. it
# still lists meta-toradex-distro, which Torizon OS 8 no longer ships).
#
# Usage: ci/mkconf.sh <tree-root> <build-dir> [channel]
#   <tree-root> is the host path of the synced tree; it is mounted at /workdir
#   inside crops, which is what the generated files refer to.
#   [channel] release (default) | integration | next.
set -euo pipefail

CI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TREE="${1:?tree root}"
BUILD_DIR="${2:?build dir}"
CHANNEL="${3:-release}"
TEMPLATE="$TREE/layers/meta-torizon-bsp/conf/template/bblayers.conf"
OVERLAY_LAYERS=(meta-swupdate meta-rauc meta-torizon-ab)

[ -f "$TEMPLATE" ] || { echo "mkconf: no bblayers template at $TEMPLATE" >&2; exit 2; }
mkdir -p "$BUILD_DIR/conf"

{
  echo "# Generated by ci/mkconf.sh from meta-torizon-bsp's bblayers template. Do not edit."
  # Set before the template's 'EXTRALAYERS ?= ""' so that default does not apply.
  echo 'EXTRALAYERS = " \'
  for l in "${OVERLAY_LAYERS[@]}"; do echo '  ${OEROOT}/layers/'"$l"' \'; done
  echo '"'
  echo
  sed 's|@OEROOT@|/workdir|g' "$TEMPLATE" | while IFS= read -r line || [ -n "$line" ]; do
    if [[ "$line" =~ \$\{OEROOT\}/layers/([^[:space:]]+) ]] && [ ! -d "$TREE/layers/${BASH_REMATCH[1]}" ]; then
      echo "mkconf: WARNING: template lists layers/${BASH_REMATCH[1]}, not in the tree; dropped" >&2
      continue
    fi
    printf '%s\n' "$line"
  done
} > "$BUILD_DIR/conf/bblayers.conf"

cp "$CI_DIR/conf/local.conf" "$BUILD_DIR/conf/local.conf"

# Shared host caches (mounted at /dl,/sstate). The hash-equivalence DB must sit
# next to a shared sstate, as upstream's site.conf does.
printf 'DL_DIR = "/dl"\nSSTATE_DIR = "/sstate"\nBB_HASHSERVE_DB_DIR = "${SSTATE_DIR}"\n' \
  > "$BUILD_DIR/conf/auto.conf"

# Floating channels track upstream's integration/next manifests, which need the
# newest u-boot/kernel/aktualizr — upstream's setup-environment adds exactly this
# for its integration.xml/next.xml (it detects them by the manifest's file name;
# CI passes the channel explicitly instead).
case "$CHANNEL" in
  integration|next) printf '\nDISTROOVERRIDES .= ":use-head-next"\nINHERIT += "buildhistory"\n' \
                      >> "$BUILD_DIR/conf/auto.conf" ;;
esac
